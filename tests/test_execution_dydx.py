def canned(ex, answers):
    """Replace the gate's HTTP with canned answers; the endpoint fence still applies."""
    ex.dry_run = False
    sent = []

    async def send(method, url, *, params=None, data=None, json_body=None, headers=None, content=None, timeout=15.0):
        assert ex.allows(url), url
        sent.append({"method": method, "url": url, "params": params, "content": content, "headers": ex._scrub(headers)})
        return sent[-1], answers.pop(0)
    ex._send = send
    return sent


# An independent protobuf reader: {field: [values]}, varint/fixed32 as int, length-delimited as bytes.
def _vi(b, i):
    n = s = 0
    while True:
        c = b[i]
        i, n, s = i + 1, n | (c & 0x7F) << s, s + 7
        if not c & 0x80:
            return n, i


def decode(b: bytes) -> dict:
    i, out = 0, {}
    while i < len(b):
        tag, i = _vi(b, i)
        f, wt = tag >> 3, tag & 7
        if wt == 0:
            v, i = _vi(b, i)
        elif wt == 5:
            v, i = int.from_bytes(b[i:i + 4], "little"), i + 4
        elif wt == 2:
            n, i = _vi(b, i)
            v, i = b[i:i + n], i + n
        else:
            raise ValueError(wt)
        out.setdefault(f, []).append(v)
    return out


def tx_of(req: dict) -> bytes:
    return base64.b64decode(json.loads(req["content"])["tx_bytes"])


def order_of(tx: bytes) -> tuple[dict, dict, dict]:
    """(the Order's fields, its OrderId's fields, the Any's type url) out of a TxRaw."""
    body = decode(decode(tx)[1][0])
    anym = decode(body[1][0])
    order = decode(decode(anym[2][0])[1][0])
    return order, decode(order[1][0]), anym[1][0].decode()


