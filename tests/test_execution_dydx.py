def test_cancel_dry_run(tmp_path):
    ex = make(tmp_path)
    placed = run(ex.place(Order("dydx", "ETH-USD", "sell", 0.5, price=2_600.0, notional_usd=1_300.0, client_id="7")))
    res = run(ex.cancel(placed.order_id, "ETH-USD"))
    assert res.ok and res.status == "dry-run" and res.order_id == placed.order_id
    body = decode(decode(tx_of(res.request))[1][0])
    anym = decode(body[1][0])
    assert anym[1][0] == b"/dydxprotocol.clob.MsgCancelOrder"
    msg = decode(anym[2][0])
    oid = decode(msg[1][0])
    assert oid[2] == [7] and oid[3] == [LONG_TERM] and oid[4] == [1] and msg[3] == [NOW + 86_400] and 2 not in msg
    placed = run(ex.place(Order("dydx", "BTC-USD", "buy", 0.02, notional_usd=1_600.0, client_id="9")))
    msg = decode(decode(decode(decode(tx_of(run(ex.cancel(placed.order_id, "BTC-USD")).request))[1][0])[1][0])[2][0])
    assert decode(msg[1][0])[2] == [9] and msg[2] == [CHAIN["height"] + 10] and 3 not in msg
    res = run(ex.cancel("00000000-0000-5000-8000-000000000000", "BTC-USD"))
    assert not res.ok and "unknown order" in res.error


