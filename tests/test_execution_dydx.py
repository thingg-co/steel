def test_wire_format():
    assert _varint(0) == b"\x00" and _varint(1) == b"\x01" and _varint(300) == b"\xac\x02" and _varint(2**32 - 1) == b"\xff\xff\xff\xff\x0f"
    assert _u(3, 0) == b"" and _u(3, 64) == b"\x18\x40" and _u(2, 1) == b"\x10\x01"
    assert _f32(2, 0) == b"" and _f32(2, 1) == b"\x15\x01\x00\x00\x00" and _f32(6, 2**32 - 1) == b"\x35\xff\xff\xff\xff"
    assert _ld(1, "") == b"" and _ld(1, "ab") == b"\x0a\x02ab" and _ld(2, b"\x01") == b"\x12\x01\x01"
    assert decode(_u(3, 64) + _f32(2, 7) + _ld(1, "ab")) == {3: [64], 2: [7], 1: [b"ab"]}


