def test_quantums_and_subticks():
    for m in MARKETS.values():                      # the venue's own tick and step are the formula's fixed points
        assert quantums(float(m["stepSize"]), m) == m["stepBaseQuantums"]
        assert subticks(float(m["tickSize"]), m) == m["subticksPerTick"]
    btc = MARKETS["BTC-USD"]
    assert quantums(0.02, btc) == 200_000_000 and quantums(0.00015, btc) == 1_000_000 and quantums(0.00009, btc) == 0     # floored, never upsized
    assert subticks(80_000.0, btc) == 8_000_000_000 and subticks(80_000.4, btc, "buy") == 8_000_000_000 and subticks(80_000.4, btc, "sell") == 8_000_100_000
    assert quantums(0.3, btc) == 3_000_000_000                                   # Decimal, so 0.3 x 1e10 is exact
    assert quantums(1e8, MARKETS["PEPE-USD"]) == 10_000_000 and subticks(0.000004, MARKETS["PEPE-USD"]) == 40_000_000_000
    # The docs' block-data example (concepts/trading/quantums): 1479500000 quote quantums for 500000000 base quantums at
    # atomicResolution -7 is 29.59 USDC; with quantumConversionExponent -9 that is 2959000000 subticks.
    sol_like = {"atomicResolution": -7, "quantumConversionExponent": -9, "subticksPerTick": 1_000_000, "stepBaseQuantums": 1_000_000}
    assert subticks(29.59, sol_like) == 2_959_000_000 == int(Decimal(1479500000) / Decimal(500000000) * 10**9)


def test_pinned_tx_decodes_and_verifies(tmp_path):
    ex = make(tmp_path)
    res = run(ex.place(Order("dydx", "BTC-USD", "buy", 0.02, notional_usd=1_600.0, client_id="steel-42")))
    assert res.ok and res.status == "dry-run" and res.venue == "dydx" and not res.error
    assert res.request["url"] == "https://dydx-ops-rest.kingnodes.com" + BROADCAST and res.request["method"] == "POST"
    assert json.loads(res.request["content"])["mode"] == "BROADCAST_MODE_SYNC" and res.request["headers"] == {"Content-Type": "application/json"}
    assert KEY.hex() not in json.dumps(res.request) and KEY.hex() not in json.dumps(res.raw)
    tx = tx_of(res.request)
    assert base64.b64encode(tx).decode() == TX
    assert sign_tx(ex.key(), [decode(decode(tx)[1][0])[1][0]], "dydx-mainnet-1", 64218, 7) == tx     # deterministic
    raw = decode(tx)
    body, auth, sig = raw[1][0], raw[2][0], raw[3][0]
    assert len(sig) == 64
    r, s = int.from_bytes(sig[:32], "big"), int.from_bytes(sig[32:], "big")
    assert s <= SECP_N // 2
    doc = _ld(1, body) + _ld(2, auth) + _ld(3, "dydx-mainnet-1") + _u(4, 64218)
    pub = keys.PrivateKey(KEY).public_key.to_compressed_bytes()
    ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256K1(), pub).verify(
        utils.encode_dss_signature(r, s), hashlib.sha256(doc).digest(), ec.ECDSA(utils.Prehashed(hashes.SHA256())))
    assert decode(body)[2][0] == b"Steel"
    signer = decode(decode(auth)[1][0])
    pk = decode(signer[1][0])
    assert pk[1][0] == b"/cosmos.crypto.secp256k1.PubKey" and decode(pk[2][0])[1][0] == pub
    assert decode(decode(signer[2][0])[1][0]) == {1: [1]} and signer[3][0] == 7           # SIGN_MODE_DIRECT, the sequence
    assert decode(decode(auth)[2][0]) == {2: [1_000_000]}                                   # gas limit, no coins
    order, oid, url = order_of(tx)
    assert url == "/dydxprotocol.clob.MsgPlaceOrder"
    cid = int.from_bytes(hashlib.sha256(b"steel-42").digest()[:4], "big")
    assert decode(oid[1][0]) == {1: [ADDRESS.encode()]} and oid[2] == [cid] and 3 not in oid and 4 not in oid    # subaccount 0, flags 0, clob 0
    assert order[2] == [1] and order[3] == [200_000_000] and order[5] == [CHAIN["height"] + 10] and order[7] == [1] and order[9] == [1]
    assert order[4] == [subticks(82966.38957 * 1.05, MARKETS["BTC-USD"])] == [8_711_400_000] and 6 not in order and 8 not in order
    assert res.order_id == indexer_order_uuid(ADDRESS, 0, cid, 0, SHORT_TERM) == "0929ae07-41d0-5e75-85b1-af0fa445cbf0"
    assert ex.known[res.order_id]["clientId"] == cid and ex.gate.spent_day


